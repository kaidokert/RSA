//! End-to-end no_alloc PSS verify smoke test on cortex-m via
//! `rsa::pss::GenericVerifyingKey`. RSA-1024 + SHA-256 + e=65537 + salt_len=0
//! (so the signature is deterministic from key + message; no RNG involved).
//! Vector captured from the same `pss::SigningKey` running on host.

