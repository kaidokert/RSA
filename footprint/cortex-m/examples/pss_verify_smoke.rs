#[cortex_m_rt::entry]
fn main() -> ! {
    type U1024 = FixedUInt<u8, 128>;

    let key = match public_key_from_be_bytes::<U1024>(&MODULUS, 65537) {
        Ok(k) => GenericVerifyingKey::<Sha256, _, _>::new_with_salt_len(k, 0),
        Err(e) => {
            hprintln!("pss_verify_smoke: key build failed: {:?}", e);
            debug::exit(debug::EXIT_FAILURE);
            loop {}
        }
    };

    let prehash = Sha256::digest(MESSAGE);
    let signature = GenericSignature::from(U1024::from_be_bytes(&SIGNATURE));

    match key.verify_prehash(&prehash, &signature) {
        Ok(()) => {
            hprintln!("pss_verify_smoke: ok");
            debug::exit(debug::EXIT_SUCCESS);
        }
        Err(e) => {
            hprintln!("pss_verify_smoke: verify failed: {:?}", e);
            debug::exit(debug::EXIT_FAILURE);
        }
    }

    loop {}
}
