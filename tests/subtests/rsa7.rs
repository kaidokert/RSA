use core::convert::{AsRef, Into, TryInto};
use fixed_bigint::{FixedUInt, MachineWord};
use rsa_heapless::pkcs1v15::VerifyingKey;
use rsa_heapless::signature::Verifier;
use rsa_heapless::RsaPublicKey;
use sha1::Sha1;

pub const DESC: &str = "[768-bit]";

/// Verify example PKCS1v15 signature with RSA public key
pub fn rsa_signature_verify<T: MachineWord + core::fmt::Debug, const N: usize>(
) -> Result<(), rsa_heapless::signature::Error> {
    let data = b"hello world!";
    // Modulus (768-bit)
    let modulus: [u8; 96] = [
        //big-endian
        0xAF, 0x86, 0xDF, 0xC2, 0x81, 0x3D, 0x24, 0x4E, 0xB4, 0xB5, 0xAF, 0x68, 0x35, 0x5C, 0x01,
        0x13, 0x24, 0x2D, 0x47, 0x30, 0x76, 0xD4, 0x4E, 0xD6, 0x54, 0xB0, 0x07, 0x24, 0x40, 0x9B,
        0x2A, 0x2A, 0x51, 0x12, 0x09, 0x73, 0xF6, 0xAE, 0xF4, 0x98, 0xAA, 0x52, 0x31, 0x8F, 0x52,
        0xF3, 0xC6, 0x55, 0xFF, 0x0B, 0x7E, 0x52, 0x9E, 0x32, 0xAA, 0x0D, 0x4C, 0x99, 0x86, 0xC2,
        0xD2, 0x77, 0x5D, 0x11, 0xB0, 0xEE, 0xF7, 0x84, 0xF9, 0xA2, 0x21, 0x6B, 0xCE, 0x95, 0xC6,
        0x29, 0x9B, 0x5D, 0x5F, 0x2B, 0x9A, 0x3B, 0xC0, 0x6B, 0xE8, 0xF2, 0x8A, 0xD3, 0x2A, 0xB6,
        0x1E, 0x62, 0x84, 0x54, 0x1C, 0xDB,
    ];

    // Signature
    let signature: [u8; 96] = [
        //big-endian
        0x35, 0x75, 0x13, 0xEF, 0x8F, 0x5B, 0xB8, 0xD1, 0x1A, 0x22, 0xEA, 0x47, 0xAF, 0x94, 0x50,
        0x75, 0x06, 0x98, 0x80, 0x61, 0xE7, 0x6D, 0x04, 0x87, 0xA6, 0xE3, 0xBC, 0xE4, 0x85, 0xAD,
        0x24, 0x07, 0x4C, 0xF2, 0x37, 0x24, 0x7E, 0xB2, 0xF6, 0x4D, 0xA2, 0x51, 0x4E, 0x4B, 0x2F,
        0x45, 0xD1, 0xCF, 0x2C, 0x19, 0xA5, 0x1D, 0x31, 0x94, 0xDD, 0xD4, 0xA4, 0x9B, 0x04, 0x58,
        0x02, 0xDF, 0xE7, 0x8F, 0x03, 0xA6, 0x63, 0xEC, 0x6E, 0x37, 0x12, 0xDB, 0xFF, 0xDC, 0x48,
        0x4A, 0x9A, 0xB4, 0x77, 0x30, 0x6F, 0x57, 0x61, 0xB4, 0xFF, 0xD7, 0xF3, 0x63, 0x6A, 0xBE,
        0xE1, 0x02, 0x81, 0x23, 0xAE, 0xC3,
    ];
    let n = FixedUInt::<T, N>::from_be_bytes(&modulus);
    let key = RsaPublicKey::new(n, 3u8.into())?;
    let sig_ref: &[u8] = signature.as_ref();
    let verifying_key = VerifyingKey::<Sha1, _>::new(key);
    verifying_key.verify(data, &sig_ref.try_into()?)
}
